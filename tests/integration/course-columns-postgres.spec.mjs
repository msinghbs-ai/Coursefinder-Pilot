test('12: a Viewer (read-only role) saves only its own layout; two people never change each other\'s', async ({ browser }) => {
  const v = await open(browser, 'viewer')
  await v.page.locator('[data-columns-toggle]').click()
  await v.page.locator('[data-col-toggle="provider_name"]').uncheck()
  await saved(v.page)
  expect(await headers(v.page)).not.toContain('provider_name')
  const a = await open(browser, 'admin')
  expect(await headers(a.page)).toContain('provider_name')
  await a.page.locator('[data-columns-toggle]').click()
  await a.page.locator('[data-col-toggle="country_name"]').check()
  await saved(a.page)
  await v.context.close()
  const v2 = await open(browser, 'viewer')
  await expect.poll(() => headers(v2.page)).not.toContain('provider_name')
  expect(await headers(v2.page)).not.toContain('country_name')
  await v2.page.locator('[data-columns-toggle]').click()
  await v2.page.locator('[data-columns-reset]').click()
  await expect(v2.page.locator('[data-layout-ack="success"]')).toContainText('Default layout restored')
  await a.context.close(); await v2.context.close()
})

