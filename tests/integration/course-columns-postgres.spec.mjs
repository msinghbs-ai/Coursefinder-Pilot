// Guards: Platform Admin mandate 5 Nov 2026 17:31, Course Catalogue columns: the real Admin UI against isolated PostgreSQL (mandate §10 cases 1-15).
// The Course catalogue's two RPCs (admin_read courses_page, admin_table_layout) run real SQL on the production-representative fixture
// (tests/fixtures/course-catalogue-columns: 39 tables at production parity, the live page functions, 35,700 courses). Everything else on the
// page comes from the shared admin mock. Each person is a separate browser context (its own storage), so a new context is another browser or a
// sign-in after signing out.
import { test, expect } from '@playwright/test'
import { mockAdmin } from '../uat/support/admin-mock.mjs'

const DB = 'http://127.0.0.1:55434'
const RANK = { admin: 6, operator2: 4, viewer: 1 }
async function open(browser, who, { viewport } = {}) {
  const context = await browser.newContext(viewport ? { viewport } : {})
  const page = await context.newPage()
  await mockAdmin(page, { rank: RANK[who] })
  const forward = async route => {
    const res = await page.request.post(DB + new URL(route.request().url()).pathname, { data: route.request().postDataJSON(), headers: { 'x-fixture-user': who } })
    await route.fulfill({ response: res })
  }
  await page.route('https://example.supabase.co/rest/v1/rpc/admin_read', route => route.request().postDataJSON()?.p_operation === 'courses_page' ? forward(route) : route.fallback())
  await page.route('https://example.supabase.co/rest/v1/rpc/admin_table_layout', forward)
  await page.goto('/#courses')
  await expect(page.getByRole('heading', { name: 'Course catalogue' })).toBeVisible()
  await expect(page.locator('table[data-table="course"] tbody tr[data-row]').first()).toBeVisible()
  return { context, page }
}
const headers = page => page.locator('table[data-table="course"] thead th[data-col]').evaluateAll(ths => ths.map(th => th.dataset.col))
const saved = page => expect(page.locator('[data-layout-ack="success"]')).toContainText(/saved to your account|restored/i)
const firstTitle = page => page.locator('table[data-table="course"] tbody tr[data-row]').first().locator('td').first()
const DEFAULT = ['canonical_title', 'course_code', 'provider_name', 'subdivision_name', 'city_names', 'level_name', 'field_of_study', 'intl_fee_amount', 'fee_amount', 'completeness_score_v2', 'adapter_state', 'last_verified_at', 'last_modified_at', 'last_admitted_at']

test('1, 2, 3, 5: show, hide, reorder and resize are saved to the account and restored in another browser after signing in again', async ({ browser }) => {
  const { context, page } = await open(browser, 'operator2')
  expect(await headers(page)).toEqual(DEFAULT)
  await page.locator('[data-columns-toggle]').click()
  await expect(page.locator('[data-columns-count]')).toHaveText('14 of 36')
  await page.getByLabel('Search columns').fill('campus')
  await expect(page.locator('[data-col-toggle]')).toHaveCount(1)
  await page.locator('[data-col-toggle="campus_count"]').check()
  await page.getByLabel('Search columns').fill('')
  await page.locator('[data-col-toggle="level_name"]').uncheck()
  // keyboard reorder: Last data admitted moves two places to the left
  const left = page.locator('[data-col-move="last_admitted_at:-1"]')
  await left.focus(); await page.keyboard.press('Enter'); await expect(page.locator('[data-col-move="last_admitted_at:-1"]')).toBeFocused(); await page.keyboard.press('Enter')
  await page.keyboard.press('Escape')
  // keyboard resize: the Provider column grows 48 px
  const before = await page.locator('th[data-col="provider_name"]').evaluate(th => Math.round(th.getBoundingClientRect().width))
  await page.locator('[data-col-resize="provider_name"]').focus()
  for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowRight')
  await saved(page)
  const order = await headers(page)
  expect(order).not.toContain('level_name')
  expect(order).toContain('campus_count')
  expect(order.indexOf('last_admitted_at')).toBe(order.indexOf('adapter_state') + 1)
  await context.close()
  // signed out; signed in again in a new browser with no local storage: the layout comes back from the server
  const again = await open(browser, 'operator2')
  await expect.poll(() => headers(again.page)).toEqual(order)
  const width = await again.page.locator('th[data-col="provider_name"]').evaluate(th => Math.round(th.getBoundingClientRect().width))
  expect(Math.abs(width - (before + 48))).toBeLessThanOrEqual(2)
  // 4: Reset to default, then Restore last saved
  await again.page.locator('[data-columns-toggle]').click()
  await again.page.locator('[data-columns-reset]').click()
  await expect(again.page.locator('[data-layout-ack="success"]')).toContainText('Default layout restored')
  expect(await headers(again.page)).toEqual(DEFAULT)
  await again.page.locator('[data-columns-restore]').click()
  await expect(again.page.locator('[data-layout-ack="success"]')).toContainText('Last saved layout restored')
  expect(await headers(again.page)).toEqual(order)
  await again.context.close()
})

test('6, 9, 10: Last data admitted sorts the whole filtered set on the server, across pages, and is kept with the layout', async ({ browser }) => {
  const { context, page } = await open(browser, 'admin')
  const head = page.locator('th[data-col="last_admitted_at"] button')
  await head.click()
  await expect(page.locator('[data-active-sort]')).toContainText('Last data admitted, oldest first')
  await expect(firstTitle(page)).toContainText('Kestrel Oldest Admission')
  await head.click()
  await expect(page.locator('[data-active-sort]')).toHaveAttribute('data-active-sort', 'admitted:desc')
  await expect(page.locator('[data-active-sort]')).toContainText('Last data admitted, newest first (Unknown last)')
  await expect(firstTitle(page)).toContainText('Kestrel Newest Admission')
  await expect(page.locator('th[data-col="last_admitted_at"]')).toHaveAttribute('aria-sort', 'descending')
  const lastOfPage1 = await page.locator('table[data-table="course"] tbody tr[data-row]').last().locator('[data-admitted]').getAttribute('data-at')
  await page.getByRole('button', { name: 'Next' }).click()
  await expect(page.getByText(/Page\s*2\s*of/)).toBeVisible()
  await expect(firstTitle(page)).not.toContainText('Kestrel Newest Admission')
  const firstOfPage2 = await page.locator('table[data-table="course"] tbody tr[data-row]').first().locator('[data-admitted]').getAttribute('data-at')
  expect(lastOfPage1).toBeTruthy(); expect(firstOfPage2).toBeTruthy()
  expect(new Date(firstOfPage2).getTime()).toBeLessThanOrEqual(new Date(lastOfPage1).getTime())
  await saved(page)
  await context.close()
  const again = await open(browser, 'admin')
  await expect(again.page.locator('[data-active-sort]')).toHaveAttribute('data-active-sort', 'admitted:desc')
  await expect(firstTitle(again.page)).toContainText('Kestrel Newest Admission')
  await again.context.close()
})

